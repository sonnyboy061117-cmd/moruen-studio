export function buildOriginalPrompt({ topic, length, style, domain, withImages }) {
  // 把"字数选项"转成"严格区间",抑制 LLM 长度漂移
  const range = getLengthRange(length);
  return `请以"${topic}"为题,写一篇 ${domain} 领域 ${style} 类文章。
${withImages ? '文中需要 1-2 处自然提到配图位置(用[配图]占位)。' : ''}

【字数要求 - 严格遵守】
- 目标字数:${length} 字
- 允许范围:${range.min} - ${range.max} 字(下限不能少,上限不能超)
- 写完后请自检:如果超出 ${range.max} 字必须精简;如果不到 ${range.min} 字必须扩写
- 不要写"差不多就行",字数控制是硬指标

【结构要求 - 严格遵守】
- 必须按"开篇 → 主体(2-4 段) → 结尾"自然分段
- 段与段之间必须用一个空行隔开(不要堆成一大段)
- 每段 80-200 字,不要超长段落(超过 250 字必须断段)
- 开篇用具体场景或反问切入,不要"随着社会的不断发展"这类套话
- 中间给 2-3 个真实可信的例子,带具体数字/地点/时间
- 结尾给出"明天就能做"的具体建议,不要"综上所述"
- 像一位有阅历的朋友跟你聊天,语气自然`;
}

// 字数档位 -> 严格区间
export function getLengthRange(target) {
  // 短 / 中 / 长 三个档,允许 ±15% 浮动,最多 ±200 字
  const tolerance = Math.min(200, Math.max(80, Math.round(target * 0.15)));
  return { min: target - tolerance, max: target + tolerance };
}

export function buildBatchRewritePrompt({ originalText, strength, logic, targetLength, angle }) {
  return `你是改写老手。请把下面这篇文章改写成"完全不像原版,但核心信息保留"的新版。
改写强度: ${strength}
改写逻辑: ${logic.join('、')}
目标字数: ${targetLength}
切入角度: ${angle || '保持原角度'}

原文:
"""
${originalText}
"""

要求:
1. 句式、词汇、段落顺序全部打散重组,不要只是换同义词。
2. 加入你自己的"看法"和"举例",但不能编造核心数据。
3. 标题也重新拟一个,符合"像人写的"标准。
4. 不要用 Markdown 标题符号,纯文本段落,空行分隔。`;
}

export function buildUniversalPrompt({ text, strength, audience, keywords, tone, length, onlyDeAI }) {
  let extra = '';
  if (audience && audience !== '通用') extra += `\n目标读者: ${audience}。`;
  if (keywords) extra += `\n必须保留这些核心关键词: ${keywords}。`;
  if (tone) extra += `\n语气: 偏口语/轻松/朋友聊天,不要正式书面。`;
  if (length && length !== '保持原长度') extra += `\n长度: ${length}。`;

  if (onlyDeAI) {
    return `你只做一件事:把下面这段文字改得"完全不像 AI 写的",其他都不动(标题、结构、字数都保留)。
其他要求:
- 句式全部重排,不要保留原顺序
- 加入口语连接词("其实""说白了""坦白讲"等)
- 给具体数字、场景、个人感受
- 删除所有"首先/其次/最后""综上所述"等套话${extra}

原文:
"""
${text}
"""`;
  }

  return `请按以下规格改写这段文字:
- 改写强度: ${strength}
${extra}

原文:
"""
${text}
"""`;
}

