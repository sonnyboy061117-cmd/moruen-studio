// 判断原文开篇方式
function detectOpeningStyle(text) {
  const firstPara = text.split('\n\n')[1] || text.split('\n\n')[0]; // 跳过标题
  const first100 = firstPara.substring(0, 100);

  if (/最后|结果|现在|如今|三年后/.test(first100)) return '倒叙式';
  if (/不是|不该|其实|说白了|反而/.test(first100)) return '反常识观点式';
  if (/\d+%|\d+人|\d+亿|数据显示|调查/.test(first100)) return '数据现象切入式';
  if (/[？?]/.test(first100) && first100.indexOf('？') < 50) return '提问式';
  if (/那天|有一次|记得|我认识/.test(first100)) return '场景描述式';

  return '其他';
}

// 判断原文论证结构类型
function detectStructureType(text) {
  const hasStory = /我认识|有一次|那天|记得/.test(text);
  const hasConclusion = text.split('\n\n')[1]?.length < 200; // 开头很短通常是结论先行
  const hasQuestion = /怎么办|如何|为什么/.test(text.split('\n\n')[0]);

  if (hasQuestion) return '问题分析方案型';
  if (hasConclusion) return '先结论后论据型';
  if (hasStory) return '故事叙述型';

  return '其他';
}

// 打乱数组顺序（用于中度/深度改写）
function shuffleArray(arr) {
  // 使用固定的打乱算法（倒序 + 前后对调）
  const result = [...arr];
  result.reverse();
  if (result.length >= 4) {
    [result[0], result[result.length - 1]] = [result[result.length - 1], result[0]];
  }
  return result;
}
